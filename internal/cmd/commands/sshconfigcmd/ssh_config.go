var (
	_ cli.Command             = (*Command)(nil)
	_ cli.CommandAutocomplete = (*Command)(nil)
)

type Command struct {
	*base.Command

	flagScopeId   string
	flagRecursive bool
	flagBinary    string
}

type configAlias struct {
	value   string
	scopeId string
}

func (c *Command) Synopsis() string {
	return "Generate an SSH config snippet that routes hosts through Dumpling"
}

func (c *Command) Help() string {
	return base.WrapForHelpText([]string{
		"Usage: dumpling ssh-config [options]",
		"",
		"  This command lists the aliases you can access and writes an SSH config",
		"  snippet with one Host block per alias. Each block uses",
		"  'connect -format ssh-proxy' as its ProxyCommand, so a plain 'ssh <alias>'",
		"  routes the connection through Dumpling to the alias's target. No SSH",
		"  custom SSH client or background agent is required.",
		"",
		"  Append the output to ~/.ssh/config (or a file you Include from it):",
		"",
		"      $ dumpling ssh-config >> ~/.ssh/config",
		"",
		"  Then connect with:",
		"",
		"      $ ssh my-target",
		"",
		"",
	}) + c.Flags().Help()
}

func (c *Command) Flags() *base.FlagSets {
	set := c.FlagSet(base.FlagSetHTTP | base.FlagSetClient | base.FlagSetOutputFormat)
	f := set.NewFlagSet("SSH Config Options")

	f.StringVar(&base.StringVar{
		Name:       "scope-id",
		Target:     &c.flagScopeId,
		EnvVar:     "DUMPLING_SSH_CONFIG_SCOPE_ID",
		Default:    "global",
		Completion: complete.PredictAnything,
		Usage:      "The scope to list aliases from. If unset, the global scope is used.",
	})

	f.BoolVar(&base.BoolVar{
		Name:       "recursive",
		Target:     &c.flagRecursive,
		Default:    true,
		EnvVar:     "DUMPLING_SSH_CONFIG_RECURSIVE",
		Completion: complete.PredictAnything,
		Usage:      "Include aliases from child scopes of -scope-id.",
	})

	f.StringVar(&base.StringVar{
		Name:       "binary",
		Target:     &c.flagBinary,
		EnvVar:     "DUMPLING_SSH_CONFIG_BINARY",
		Completion: complete.PredictAnything,
		Default:    "dumpling",
		Usage:      "The Dumpling binary to reference in the generated ProxyCommand. Set this if the binary is not named 'dumpling' or is not on the SSH process's PATH.",
	})

	return set
}

func (c *Command) AutocompleteArgs() complete.Predictor {
	return complete.PredictAnything
}

func (c *Command) AutocompleteFlags() complete.Flags {
	return c.Flags().Completions()
}

func (c *Command) Run(args []string) int {
	f := c.Flags()
	if err := f.Parse(args); err != nil {
		c.PrintCliError(err)
		return base.CommandUserError
	}

	client, err := c.Client()
	if c.WrapperCleanupFunc != nil {
		defer func() {
			if err := c.WrapperCleanupFunc(); err != nil {
				c.PrintCliError(fmt.Errorf("Error cleaning kms wrapper: %w", err))
			}
		}()
	}
	if err != nil {
		c.PrintCliError(fmt.Errorf("Error creating API client: %w", err))
		return base.CommandCliError
	}

	aliasClient := aliases.NewClient(client)

	var opts []aliases.Option
	if c.flagRecursive {
		opts = append(opts, aliases.WithRecursive(true))
	}
	list, err := aliasClient.List(c.Context, c.flagScopeId, opts...)
	if err != nil {
		if apiErr := api.AsServerError(err); apiErr != nil {
			c.PrintApiError(apiErr, "Error from controller when listing aliases")
			return base.CommandApiError
		}
		c.PrintCliError(fmt.Errorf("Error listing aliases: %w", err))
		return base.CommandCliError
	}

	var configAliases []configAlias
	for _, item := range list.GetItems() {
		if item.Value != "" && item.ScopeId != "" {
			configAliases = append(configAliases, configAlias{value: item.Value, scopeId: item.ScopeId})
		}
	}
	c.UI.Output(renderSSHConfig(configAliases, c.flagBinary))

	return base.CommandSuccess
}

func renderSSHConfig(aliases []configAlias, binary string) string {
	sort.Slice(aliases, func(i, j int) bool {
		if aliases[i].value == aliases[j].value {
			return aliases[i].scopeId < aliases[j].scopeId
		}
		return aliases[i].value < aliases[j].value
	})

	counts := make(map[string]int, len(aliases))
	for _, item := range aliases {
		counts[item.value]++
	}

	var out strings.Builder
	out.WriteString("# Generated by dumpling ssh-config. Do not edit by hand.\n")
	out.WriteString("# Append to ~/.ssh/config, then connect with: ssh <alias>\n\n")
	usedHosts := make(map[string]struct{}, len(aliases))
	for _, item := range aliases {
		host := item.value
		if counts[item.value] > 1 {
			host = item.value + "-" + item.scopeId
		}
		baseHost := host
		for suffix := 2; ; suffix++ {
			if _, exists := usedHosts[host]; !exists {
				break
			}
			host = fmt.Sprintf("%s-%d", baseHost, suffix)
		}
		usedHosts[host] = struct{}{}

		fmt.Fprintf(&out, "Host %s\n", host)
		fmt.Fprintf(&out, "  ProxyCommand %s connect -format ssh-proxy -alias %s -alias-scope-id %s\n\n",
			shellQuote(strings.ReplaceAll(binary, "%", "%%")), shellQuote(item.value), shellQuote(item.scopeId))
	}
	return out.String()
}

// shellQuote quotes one argument for the shell that OpenSSH uses to execute a
// ProxyCommand. Alias values and scope IDs are validated by the controller,
// but the binary path may contain spaces or shell metacharacters.
func shellQuote(value string) string {
	return "'" + strings.ReplaceAll(value, "'", "'\\''") + "'"
}
